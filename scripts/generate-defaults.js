import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const projectRoot = path.dirname(__dirname);

function generateDefaultPrompts() {
  const defaultPromptsDir = path.join(projectRoot, 'default-prompts');
  
  if (!fs.existsSync(defaultPromptsDir)) {
    console.log('❌ default-prompts directory not found');
    return;
  }

  const folders = [];
  const prompts = {};
  
  // Read all subdirectories (folders)
  const folderNames = fs.readdirSync(defaultPromptsDir, { withFileTypes: true })
    .filter(dirent => dirent.isDirectory())
    .map(dirent => dirent.name);
    
  console.log(`📁 Found folders: ${folderNames.join(', ')}`);
  
  // Create folder objects
  folderNames.forEach(folderName => {
    folders.push({
      id: `fld_${folderName}`,
      name: folderName.charAt(0).toUpperCase() + folderName.slice(1),
      parentId: 'fld_root',
      created: new Date().toISOString()
    });
    
    // Read prompts in this folder
    const folderPath = path.join(defaultPromptsDir, folderName);
    const files = fs.readdirSync(folderPath).filter(f => f.endsWith('.txt'));
    
    console.log(`📄 Found prompts in ${folderName}: ${files.join(', ')}`);
    
    files.forEach(file => {
      const content = fs.readFileSync(path.join(folderPath, file), 'utf8');
      const prompt = parsePromptFile(content, file, `fld_${folderName}`);
      prompts[prompt.id] = prompt;
    });
  });
  
  // Generate the JavaScript file
  const output = `// Auto-generated from default-prompts/ folder
// Do not edit this file directly - edit files in default-prompts/ instead

export const DEFAULT_FOLDERS = ${JSON.stringify(folders, null, 2)};

export const DEFAULT_PROMPTS = ${JSON.stringify(prompts, null, 2)};
`;
  
  const outputPath = path.join(projectRoot, 'lib', 'default-prompts.js');
  fs.writeFileSync(outputPath, output);
  console.log(`✅ Generated lib/default-prompts.js with ${Object.keys(prompts).length} prompts in ${folders.length} folders`);
}

function parsePromptFile(content, filename, folderId) {
  const lines = content.split('\n');
  let metadata = {};
  let bodyStart = 0;
  
  // Parse header if it exists
  if (lines[0] === '---') {
    for (let i = 1; i < lines.length; i++) {
      if (lines[i] === '---') {
        bodyStart = i + 1;
        break;
      }
      const [key, ...values] = lines[i].split(':');
      if (key && values.length) {
        const value = values.join(':').trim();
        metadata[key.trim()] = key.trim() === 'tags' ? 
          value.split(',').map(t => t.trim()) : value;
      }
    }
  }
  
  const body = lines.slice(bodyStart).join('\n').trim();
  const fileBaseName = path.basename(filename, '.txt');
  
  return {
    id: `pmt_${fileBaseName.replace(/[^a-z0-9]/gi, '_')}`,
    title: metadata.title || fileBaseName.replace(/[-_]/g, ' ').replace(/\b\w/g, l => l.toUpperCase()),
    body: body,
    folderId: folderId,
    tags: metadata.tags || [],
    created: new Date().toISOString(),
    lastUsed: null
  };
}

// Run the script
generateDefaultPrompts();